$ErrorActionPreference = 'Stop'

Write-Host '=== Neral self-hosted runner launcher ==='
Write-Host 'This script only starts an already configured GitHub Actions runner.'
Write-Host 'It does not modify Neral weights or training data.'

$candidates = @()
if ($env:NERAL_RUNNER_DIR) { $candidates += $env:NERAL_RUNNER_DIR }
$candidates += @(
  'C:\actions-runner',
  'C:\github-actions-runner',
  (Join-Path $env:USERPROFILE 'actions-runner'),
  (Join-Path $env:USERPROFILE 'github-actions-runner')
)

$runner = $null
foreach ($dir in ($candidates | Select-Object -Unique)) {
  if (-not $dir) { continue }
  $run = Join-Path $dir 'run.cmd'
  if (Test-Path $run -PathType Leaf) {
    $runner = (Resolve-Path $dir).Path
    break
  }
}

if (-not $runner) {
  Write-Host ''
  Write-Host 'No existing GitHub Actions runner installation was found.' -ForegroundColor Yellow
  Write-Host 'GitHub recommends C:\actions-runner on Windows.'
  Write-Host 'Open the repository runner setup page and follow the Windows/x64 commands once:'
  Write-Host 'https://github.com/Cola968/neral-helios/settings/actions/runners/new'
  Start-Process 'https://github.com/Cola968/neral-helios/settings/actions/runners/new'
  exit 2
}

Write-Host "Runner directory: $runner"

$configured = (Test-Path (Join-Path $runner '.runner') -PathType Leaf)
if (-not $configured) {
  Write-Host ''
  Write-Host 'The runner files exist, but this installation is not registered with GitHub.' -ForegroundColor Yellow
  Write-Host 'The registration token is generated by GitHub and expires after a short time.'
  Write-Host 'Open the setup page, then run the shown config.cmd command in this directory:'
  Write-Host "  $runner"
  Write-Host 'Use the custom label: neral-gpu'
  Start-Process 'https://github.com/Cola968/neral-helios/settings/actions/runners/new'
  exit 3
}

if (-not $env:NERAL_ASSETS_ROOT) {
  Write-Host 'WARNING: NERAL_ASSETS_ROOT is not set in this process. GPU status probe can still work, but Neral control/benchmark jobs need it.' -ForegroundColor Yellow
}
if (-not $env:NERAL_PYTHON) {
  Write-Host 'WARNING: NERAL_PYTHON is not set in this process. GPU status probe can still work, but Neral control/benchmark jobs need it.' -ForegroundColor Yellow
}

$nvidia = Get-Command nvidia-smi -ErrorAction SilentlyContinue
if ($nvidia) {
  Write-Host ''
  Write-Host 'Local GPU:'
  & nvidia-smi --query-gpu=name,driver_version,memory.total,temperature.gpu,power.draw --format=csv,noheader
} else {
  Write-Host 'WARNING: nvidia-smi was not found on PATH.' -ForegroundColor Yellow
}

$existing = Get-CimInstance Win32_Process -ErrorAction SilentlyContinue | Where-Object {
  $_.Name -match 'Runner\.(Listener|Worker)\.exe'
}
if ($existing) {
  Write-Host ''
  Write-Host 'A GitHub Actions runner process already appears to be running.' -ForegroundColor Green
  Write-Host 'The queued Neral GPU probes should be picked up automatically.'
  exit 0
}

Write-Host ''
Write-Host 'Starting run.cmd in a new window...'
Start-Process -FilePath (Join-Path $runner 'run.cmd') -WorkingDirectory $runner
Start-Sleep -Seconds 3

$started = Get-CimInstance Win32_Process -ErrorAction SilentlyContinue | Where-Object {
  $_.Name -match 'Runner\.(Listener|Worker)\.exe'
}
if ($started) {
  Write-Host 'Runner process started. Leave its window open.' -ForegroundColor Green
  Write-Host 'GitHub already has queued read-only Neral GPU probes; one should start automatically.'
  exit 0
}

Write-Host 'run.cmd was launched, but the listener process was not detected yet.' -ForegroundColor Yellow
Write-Host 'Check the new runner window for the exact GitHub error message.'
exit 4
