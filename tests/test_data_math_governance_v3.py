def test_quality_rejects_short_secret_and_broken_unicode():
    assert "too_short" in assess_text("hello").reasons
    bad = ("Useful explanatory text " * 30) + " api_key = supersecretvalue "
    assert "secret_like_pattern" in assess_text(bad).reasons
    broken = ("normal words " * 30) + "\ufffd"
    assert "replacement_character" in assess_text(broken).reasons


def test_quality_flags_pii_and_synthetic_without_silently_relabeling_source():
    text = ("This is a substantial educational paragraph about physics and algebra. " * 8) + "Contact a@example.com. Generated by ChatGPT."
    result = assess_text(text)
    assert "email_like_pii" in result.flags
    assert "synthetic_marker" in result.flags
    assert len(result.sha256_normalized) == 64


def test_minhash_detects_near_duplicate_cpu(tmp_path: Path):
    base = " ".join(f"word{i % 30}" for i in range(500))
    near = base.replace("word7", "wordSEVEN", 2)
    unrelated = " ".join(f"different{i % 41}" for i in range(500))
    a = minhash_signature(base)
    b = minhash_signature(near)
    c = minhash_signature(unrelated)
    assert signature_similarity(a, b) > signature_similarity(a, c)

    idx = MinHashLSHIndex(tmp_path / "near.sqlite3", threshold=0.75)
    try:
        first = idx.add_if_novel(base)
        second = idx.add_if_novel(near)
        third = idx.add_if_novel(unrelated)
    finally:
        idx.close()
    assert first["accepted"] is True
    assert second["accepted"] is False and second["reason"] == "near_duplicate"
    assert third["accepted"] is True


