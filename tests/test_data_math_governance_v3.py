def test_holdout_registry_is_fail_closed():
    snapshot = registry_snapshot(".")
    assert len(snapshot["registry_sha256"]) == 64
    with pytest.raises(ValueError, match="evaluation holdout"):
        assert_dataset_ids_not_holdout(["openai/gsm8k"])
    with pytest.raises(ValueError, match="unregistered"):
        assert_dataset_ids_not_holdout(["unknown/example"])
    with pytest.raises(ValueError, match="non-admitted"):
        assert_dataset_ids_not_holdout(["HuggingFaceTB/finemath"])
    assert assert_dataset_ids_not_holdout(["HuggingFaceFW/fineweb-2", "OpenAssistant/oasst2"])


