def metric_row(**overrides):
    values = {
        "nis2": 60.0,
        "validation_ce": 1.20,
        "validation_bpb": 1.73,
        "math_id_exact_pct": 10.0,
        "math_transfer_exact_pct": 6.0,
        "math_ood_exact_pct": 4.0,
        "code_pct": 60.0,
        "context_pct": 70.0,
        "reasoning_pct": 55.0,
        "instruction_pct": 55.0,
        "eos_pct": 35.0,
        "repetition_pct": 3.0,
        "utf8_pct": 100.0,
        "forgetting_score": 0.10,
    }
    values.update(overrides)
    return values


def test_pareto_gate_rejects_math_gain_that_breaks_code():
    anchor = metric_row()
    candidate = metric_row(nis2=60.5, math_id_exact_pct=14, math_transfer_exact_pct=9, math_ood_exact_pct=6, code_pct=50)
    r = assess(anchor, candidate, targeted_math=True)
    assert r["accepted"] is False
    assert "regression:code_pct" in r["blockers"]


def test_pareto_gate_rejects_id_only_math_gain():
    anchor = metric_row()
    candidate = metric_row(nis2=60.5, math_id_exact_pct=15)
    r = assess(anchor, candidate, targeted_math=True)
    assert r["accepted"] is False
    assert "math_transfer_ood_no_gain" in r["blockers"]


def test_pareto_gate_accepts_balanced_improvement():
    anchor = metric_row()
    candidate = metric_row(
        nis2=60.5,
        validation_ce=1.18,
        validation_bpb=1.70,
        math_id_exact_pct=13,
        math_transfer_exact_pct=9,
        math_ood_exact_pct=7,
        code_pct=61,
        context_pct=72,
        reasoning_pct=57,
        instruction_pct=58,
        eos_pct=40,
        repetition_pct=2,
        forgetting_score=0.08,
    )
    r = assess(anchor, candidate, targeted_math=True)
    assert r["accepted"] is True, r


def test_pareto_gate_missing_evidence_fails_closed():
    anchor = metric_row()
    candidate = metric_row()
    candidate.pop("math_ood_exact_pct")
    r = assess(anchor, candidate, targeted_math=True)
    assert r["accepted"] is False
    assert "math_ood_exact_pct" in r["missing"]
