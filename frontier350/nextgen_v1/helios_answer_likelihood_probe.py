"""Check if existing Neral weights prefer correct digits under two prompt styles.

Public development questions only. Teacher-forced next-token likelihood is NOT
chat accuracy and cannot establish model quality; never trains or saves weights.
Exact SHA-gated own checkpoint, CPU only, bounded 3x2x10 candidate scoring.
All per-candidate results remain in an existing private folder on this PC.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

from helios_guarded_preview import load_continuity_cpu
from helios_quality_diagnostic import DEV_CASES, output_target
from phoenix_continuity_cpu_probe import CONTINUITY_SHA, EXPECTED_TOKENS

EQUATIONS = ("2 + 2 =", "1 + 1 =", "7 - 4 =")
DIGITS = tuple(str(i) for i in range(10))


def score_candidate(model, torch, prefix: list[int], completion: list[int]) -> float:
    """Teacher-force each continuation token, including the very first token."""
    if not completion or len(prefix) + len(completion) > model.cfg.max_seq_len:
        raise ValueError("invalid candidate length")
    whole = prefix + completion[:-1]
    with torch.inference_mode():
        logits, _ = model(torch.tensor([whole], dtype=torch.long))
        log_probs = torch.log_softmax(logits[0, len(prefix)-1:], dim=-1)
        ids = torch.tensor(completion, dtype=torch.long)
        score = float(log_probs.gather(-1, ids[:, None]).sum().item())
    return score


def score_prompt(model, tokenizer, bos: int, torch, prompt: str, answer: str) -> dict:
    prefix = [bos, *tokenizer.encode(prompt, add_special_tokens=False).ids]
    candidates = [tokenizer.encode(" " + digit, add_special_tokens=False).ids for digit in DIGITS]
    lengths = {len(ids) for ids in candidates}
    if 0 in lengths or len(lengths) != 1 or len({tuple(ids) for ids in candidates}) != 10:
        raise ValueError("digit candidates must have unique, equal-length BPE encodings")
    logp = [score_candidate(model, torch, prefix, ids) for ids in candidates]
    best = max(range(10), key=lambda index: logp[index])
    expected = int(answer)
    ordered = sorted(range(10), key=lambda index: logp[index], reverse=True)
    margin = logp[expected] - max(value for i, value in enumerate(logp) if i != expected)
    return {"prompt": prompt, "answer_token_count": next(iter(lengths)),
            "candidate_log_likelihoods": dict(zip(DIGITS, logp)),
            "top_ranked_digit": DIGITS[best], "correct_digit_rank": ordered.index(expected) + 1,
            "correct_digit_top1": best == expected, "correct_vs_best_wrong_logprob_margin": margin}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--execute", action="store_true")
    ap.add_argument("--trusted-local-checkpoint", action="store_true")
    ap.add_argument("--assets-root", type=Path, required=True)
    ap.add_argument("--checkpoint", type=Path, required=True)
    ap.add_argument("--private-dir", type=Path, required=True)
    ap.add_argument("--output-name", required=True)
    args = ap.parse_args()
    if not args.execute or not args.trusted_local_checkpoint:
        ap.error("explicit opt-in and trusted local checkpoint required")
    if os.getenv("CUDA_VISIBLE_DEVICES") != "-1":
        ap.error("CPU-only isolation required")
    target = output_target(args.private_dir, args.output_name)
    model, tok, bos, _, processed, torch = load_continuity_cpu(args.assets_root, args.checkpoint)
    if processed != EXPECTED_TOKENS or next(model.parameters()).device.type != "cpu":
        raise RuntimeError("checkpoint/device mismatch")
    rows = []
    for (case_id, question, expected), equation in zip(DEV_CASES, EQUATIONS):
        chat = score_prompt(model, tok, bos, torch, "User: " + question + "\nAssistant:", expected)
        bare = score_prompt(model, tok, bos, torch, equation, expected)
        rows.append({"id": case_id, "correct": expected, "chat": chat, "equation": bare})
    report = {"status": "development_teacher_forced_digit_rank_not_chat_accuracy",
              "checkpoint_sha256": CONTINUITY_SHA, "processed_tokens": processed,
              "device": "cpu", "training_started": False, "model_weights_modified": False,
              "independent_holdout": False, "general_quality_improvement_proven": False,
              "note": "Digit candidate sequences include one leading space; all ten candidates have identical token counts within each prompt. No answer was generated by this test.",
              "cases": rows,
              "chat_correct_top1": sum(row["chat"]["correct_digit_top1"] for row in rows),
              "equation_correct_top1": sum(row["equation"]["correct_digit_top1"] for row in rows),
              "denominator": len(rows)}
    with target.open("x", encoding="utf-8") as stream:
        json.dump(report, stream, ensure_ascii=False, indent=2)
        stream.write("\n")
    print(json.dumps({"event": "teacher_forced_digit_rank_complete",
                      "cases": len(rows), "chat_correct_top1": report["chat_correct_top1"],
                      "equation_correct_top1": report["equation_correct_top1"],
                      "ranks": [{"id": row["id"], "chat": row["chat"]["correct_digit_rank"],
                                 "equation": row["equation"]["correct_digit_rank"]} for row in rows],
                      "private_local_output": str(target), "checkpoint_sha256": CONTINUITY_SHA,
                      "training_started": False, "general_quality_improvement_proven": False}, sort_keys=True), flush=True)


if __name__ == "__main__":
    main()
