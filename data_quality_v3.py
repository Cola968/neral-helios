from __future__ import annotations

"""CPU-only admission primitives for future Neral corpora.

The module is intentionally independent of model weights. It complements the existing mobile
feeder: exact dedup remains SHA-256 based, while this file adds a disk-backed MinHash/LSH near-
dedup lane plus conservative text-quality flags. It is an admission tool, not a claim that a
source is safe merely because it passes these heuristics.
"""

from dataclasses import dataclass, asdict
import hashlib
import json
import math
from pathlib import Path
import re
import sqlite3
import struct
import unicodedata

EMAIL = re.compile(r"\b[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}\b")
PHONE = re.compile(r"(?<!\d)(?:\+?\d[\s()./-]?){8,16}(?!\d)")
SECRET = re.compile(r"(?i)\b(?:api[_ -]?key|access[_ -]?token|secret|password|private[_ -]?key)\b\s*[:=]")
URL = re.compile(r"https?://\S+", re.I)
REPEAT_CHAR = re.compile(r"(.)\1{24,}", re.S)
BOILERPLATE = re.compile(r"(?i)(cookie settings|accept all cookies|privacy policy|terms of service|all rights reserved)")
SYNTHETIC_MARKERS = re.compile(r"(?i)(generated by (?:chatgpt|gpt-|claude|llama)|as an ai language model|synthetic (?:response|dialogue|data))")

GERMAN_HINTS = {"der", "die", "das", "und", "ist", "nicht", "mit", "für", "eine", "auf", "wird", "sind"}
ENGLISH_HINTS = {"the", "and", "is", "not", "with", "for", "this", "that", "are", "from", "will", "have"}
CODE_HINTS = ("def ", "class ", "function ", "import ", "const ", "let ", "fun ", "public static", "return ")
MATH_HINTS = ("=", "∫", "√", "sin(", "cos(", "tan(", "equation", "gleichung", "theorem", "satz")


def normalize_text(text: str) -> str:
    return " ".join(unicodedata.normalize("NFKC", text).casefold().replace("\x00", " ").split())


def exact_digest(text: str) -> str:
    return hashlib.sha256(normalize_text(text).encode("utf8")).hexdigest()


def word_shingles(text: str, width: int = 5) -> set[str]:
    words = normalize_text(text).split()
    if len(words) < width:
        return {" ".join(words)} if words else set()
    return {" ".join(words[i:i + width]) for i in range(len(words) - width + 1)}


def _hash64(seed: int, value: str) -> int:
    raw = seed.to_bytes(4, "little") + value.encode("utf8", errors="strict")
    return int.from_bytes(hashlib.blake2b(raw, digest_size=8).digest(), "little")


def minhash_signature(text: str, permutations: int = 64, shingle_width: int = 5) -> tuple[int, ...]:
    shingles = word_shingles(text, shingle_width)
    if not shingles:
        return tuple((1 << 64) - 1 for _ in range(permutations))
    return tuple(min(_hash64(seed, s) for s in shingles) for seed in range(permutations))


def signature_similarity(a: tuple[int, ...], b: tuple[int, ...]) -> float:
    if len(a) != len(b) or not a:
        raise ValueError("incompatible MinHash signatures")
    return sum(x == y for x, y in zip(a, b)) / len(a)


def language_hint(text: str) -> tuple[str, float]:
    """Cheap routing hint only; never substitutes a proper language classifier."""
    norm = normalize_text(text)
    words = set(re.findall(r"[a-zäöüß]+", norm))
    de = len(words & GERMAN_HINTS)
    en = len(words & ENGLISH_HINTS)
    code = sum(marker in norm for marker in CODE_HINTS)
    math_score = sum(marker in norm for marker in MATH_HINTS)
    scores = {"de": de, "en": en, "code": code * 2, "math": math_score}
    label, score = max(scores.items(), key=lambda kv: kv[1])
    total = sum(scores.values())
    if score == 0:
        return "unknown", 0.0
    return label, score / max(1, total)


@dataclass(frozen=True)
class QualityResult:
    accepted: bool
    reasons: tuple[str, ...]
    flags: tuple[str, ...]
    chars: int
    utf8_bytes: int
    printable_ratio: float
    alpha_ratio: float
    repeated_line_ratio: float
    language_hint: str
    language_confidence: float
    sha256_normalized: str


def assess_text(text, *, min_chars: int = 300, max_chars: int = 2_000_000) -> QualityResult:
    reasons: list[str] = []
    flags: list[str] = []
    if not isinstance(text, str):
        raise TypeError("text must be str")
    value = unicodedata.normalize("NFKC", text).replace("\x00", "")
    chars = len(value)
    if chars < min_chars:
        reasons.append("too_short")
    if chars > max_chars:
        reasons.append("too_long")
    if "\ufffd" in value:
        reasons.append("replacement_character")
    controls = sum((not ch.isprintable()) and ch not in "\n\r\t" for ch in value)
    printable_ratio = 1 - controls / max(1, chars)
    if printable_ratio < 0.985:
        reasons.append("control_characters")
    alpha = sum(ch.isalpha() for ch in value)
    alpha_ratio = alpha / max(1, chars)
    if alpha_ratio < 0.16:
        reasons.append("low_alpha_ratio")
    lines = [normalize_text(x) for x in value.splitlines() if normalize_text(x)]
    repeated_line_ratio = 0.0 if not lines else 1 - len(set(lines)) / len(lines)
    if len(lines) >= 8 and repeated_line_ratio > 0.45:
        reasons.append("repeated_lines")
    if REPEAT_CHAR.search(value):
        reasons.append("pathological_character_repetition")
    if EMAIL.search(value):
        flags.append("email_like_pii")
    if PHONE.search(value):
        flags.append("phone_like_pii")
    if SECRET.search(value):
        reasons.append("secret_like_pattern")
    boilerplate_hits = len(BOILERPLATE.findall(value))
    if boilerplate_hits >= 3:
        reasons.append("boilerplate_heavy")
    elif boilerplate_hits:
        flags.append("boilerplate_present")
    if SYNTHETIC_MARKERS.search(value):
        flags.append("synthetic_marker")
    if len(URL.findall(value)) > max(20, chars // 300):
        reasons.append("url_spam")
    lang, conf = language_hint(value)
    digest = exact_digest(value)
    return QualityResult(
        accepted=not reasons,
        reasons=tuple(sorted(set(reasons))),
        flags=tuple(sorted(set(flags))),
        chars=chars,
        utf8_bytes=len(value.encode("utf8")),
        printable_ratio=printable_ratio,
        alpha_ratio=alpha_ratio,
        repeated_line_ratio=repeated_line_ratio,
        language_hint=lang,
        language_confidence=conf,
        sha256_normalized=digest,
    )


class MinHashLSHIndex:
    """Disk-backed approximate near-duplicate index with deterministic MinHash bands."""

    def __init__(self, path: str | Path, *, permutations: int = 64, bands: int = 8, threshold: float = 0.82):
        if permutations <= 0 or bands <= 0 or permutations % bands:
            raise ValueError("permutations must divide evenly into bands")
        if not 0 < threshold <= 1:
            raise ValueError("threshold must be in (0,1]")
        self.permutations = permutations
        self.bands = bands
        self.rows_per_band = permutations // bands
        self.threshold = threshold
        self.db = sqlite3.connect(Path(path))
        self.db.execute("PRAGMA journal_mode=WAL")
        self.db.execute("CREATE TABLE IF NOT EXISTS docs (digest TEXT PRIMARY KEY, sig BLOB NOT NULL)")
        self.db.execute("CREATE TABLE IF NOT EXISTS bands (band INTEGER NOT NULL, band_hash TEXT NOT NULL, digest TEXT NOT NULL, PRIMARY KEY(band,band_hash,digest))")
        self.db.execute("CREATE INDEX IF NOT EXISTS idx_bands_lookup ON bands(band, band_hash)")

    @staticmethod
    def _pack(sig: tuple[int, ...]) -> bytes:
        return struct.pack("<" + "Q" * len(sig), *sig)

    def _unpack(self, blob: bytes) -> tuple[int, ...]:
        return struct.unpack("<" + "Q" * self.permutations, blob)

    def _band_hashes(self, sig: tuple[int, ...]):
        for band in range(self.bands):
            start = band * self.rows_per_band
            part = sig[start:start + self.rows_per_band]
            digest = hashlib.blake2b(self._pack(part), digest_size=12).hexdigest()
            yield band, digest

    def near_candidates(self, sig: tuple[int, ...]) -> set[str]:
        found: set[str] = set()
        for band, band_hash in self._band_hashes(sig):
            rows = self.db.execute("SELECT digest FROM bands WHERE band=? AND band_hash=?", (band, band_hash))
            found.update(row[0] for row in rows)
        return found

    def add_if_novel(self, text: str) -> dict:
        digest = exact_digest(text)
        if self.db.execute("SELECT 1 FROM docs WHERE digest=?", (digest,)).fetchone():
            return {"accepted": False, "reason": "exact_duplicate", "digest": digest, "similarity": 1.0}
        sig = minhash_signature(text, self.permutations)
        best_digest = None
        best_similarity = 0.0
        for candidate in self.near_candidates(sig):
            row = self.db.execute("SELECT sig FROM docs WHERE digest=?", (candidate,)).fetchone()
            if row is None:
                continue
            similarity = signature_similarity(sig, self._unpack(row[0]))
            if similarity > best_similarity:
                best_similarity, best_digest = similarity, candidate
        if best_similarity >= self.threshold:
            return {"accepted": False, "reason": "near_duplicate", "digest": digest, "near": best_digest, "similarity": best_similarity}
        packed = self._pack(sig)
        self.db.execute("INSERT INTO docs(digest,sig) VALUES(?,?)", (digest, packed))
        self.db.executemany("INSERT INTO bands(band,band_hash,digest) VALUES(?,?,?)", ((band, bh, digest) for band, bh in self._band_hashes(sig)))
        self.db.commit()
        return {"accepted": True, "reason": None, "digest": digest, "near": best_digest, "similarity": best_similarity}

    def close(self):
        self.db.commit()
        self.db.close()


def manifest_record(dataset_id: str, revision: str, result: QualityResult, near: dict, *, document_id: str) -> dict:
    if len(revision) < 12:
        raise ValueError("immutable dataset revision required")
    return {
        "dataset_id": dataset_id,
        "revision": revision,
        "document_id": document_id,
        "quality": asdict(result),
        "near_dedup": near,
        "document_boundary_preserved": True,
    }
